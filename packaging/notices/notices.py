"""Third-party notices for the compiled code in Grenslan's container.

Python packages ship their own licence files in their ``.dist-info``
directories, but their wheels often contain compiled code from other
projects: native libraries (``native.lock``) and Rust crates (listed in the
wheel's CycloneDX SBOM). This tool keeps the notices for that embedded code,
and copies the packages' own licence files into an image.

Commands:

``collect --site-packages DIR... [--cache DIR]``
    A development step, with network access. Downloads the archives in
    ``native.lock`` and every Rust crate named in the installed wheels'
    SBOMs, verifies each hash, and writes ``native/`` and ``crates.txt`` next
    to this script. Crate hashes come from the SBOM where it has them,
    otherwise from the ``Cargo.lock`` in the package's PyPI source
    distribution, itself verified against PyPI's hash. Crates fetched from a
    git commit are hashed here and the hash is recorded.

``check --site-packages DIR...``
    Offline, run during the image build. Fails unless every installed wheel
    with compiled code is accounted for at its exact version, every crate
    in the installed SBOMs has notices, every committed entry still refers to
    an installed wheel, and every installed package has licence files.

``copy-python --site-packages DIR --output DIR``
    Offline. Copies each installed package's licence files to
    ``OUTPUT/<name>-<version>/``.

Uses only the standard library. Downloads go over verified HTTPS.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import shutil
import sys
import tarfile
import tomllib
import urllib.request
import zipfile
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from urllib.parse import parse_qs, unquote, urlsplit

HERE = Path(__file__).resolve().parent
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)([-._].*)?$", re.IGNORECASE)
GIT_VCS = re.compile(r"^git\+https://github\.com/([\w.-]+)/([\w.-]+?)(?:\.git)?@([0-9a-f]{40})$")
CRATES_HEADER = (
    "Notices for the Rust crates compiled into Python wheels in Grenslan's container.\n"
    "Generated by packaging/notices/notices.py collect; do not edit.\n"
    "Each crate lists its declared licence, the wheels it is compiled into, its source and\n"
    "the licence files it ships. A text identical to one printed earlier is referenced\n"
    "instead of repeated.\n"
)


class NoticeError(Exception):
    pass


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass(frozen=True)
class Native:
    archive: str
    sha256: str
    url: str
    members: tuple[str, ...]
    embedded_in: tuple[str, ...]


@dataclass(frozen=True)
class Crate:
    name: str
    version: str
    licence: str
    kind: str  # "registry", "git" or "local"
    git: tuple[str, str, str] | None = None  # owner, repository, commit
    sha256: str | None = None


@dataclass
class Dist:
    name: str
    version: str
    path: Path
    compiled: bool
    crates: list[Crate] = field(default_factory=list)

    @property
    def pin(self) -> str:
        return f"{normalize(self.name)}=={self.version}"


def read_lock(path: Path) -> tuple[list[Native], set[str]]:
    natives: list[Native] = []
    own: set[str] = set()
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        fields = line.split()
        if not fields or fields[0].startswith("#"):
            continue
        if fields[0] == "native" and len(fields) == 6:
            _, archive, sha, url, members, embedded = fields
            if not re.fullmatch(r"[0-9a-f]{64}", sha) or "/" in archive or urlsplit(url).scheme != "https":
                raise NoticeError(f"{path.name}:{number}: invalid native entry")
            pins = tuple(_pin(value) for value in embedded.split(","))
            natives.append(Native(archive, sha, url, tuple(members.split(",")), pins))
        elif fields[0] == "own-code" and len(fields) == 2:
            own.add(_pin(fields[1]))
        else:
            raise NoticeError(f"{path.name}:{number}: unrecognised line")
    return natives, own


def _pin(value: str) -> str:
    name, separator, version = value.partition("==")
    if not separator or not name or not version:
        raise NoticeError(f"expected name==version, got {value!r}")
    return f"{normalize(name)}=={version}"


def _metadata(dist_info: Path) -> tuple[str, str]:
    text = (dist_info / "METADATA").read_text(encoding="utf-8", errors="replace")
    name = re.search(r"^Name: *(.+)$", text, re.MULTILINE)
    version = re.search(r"^Version: *(.+)$", text, re.MULTILINE)
    if name is None or version is None:
        raise NoticeError(f"{dist_info.name}: METADATA lacks Name or Version")
    return name[1].strip(), version[1].strip()


def _licence_expression(component: dict[str, object]) -> str:
    parts = []
    for entry in component.get("licenses", []) or []:  # type: ignore[attr-defined]
        if "expression" in entry:
            parts.append(" ".join(str(entry["expression"]).split()))
        elif "license" in entry:
            licence = entry["license"]
            parts.append(str(licence.get("id") or licence.get("name") or "unknown"))
    return " AND ".join(parts) or "not declared"


def _crate(component: dict[str, object]) -> Crate | None:
    purl = str(component.get("purl", ""))
    if not purl.startswith("pkg:cargo/"):
        return None
    location, _, query = purl.removeprefix("pkg:cargo/").partition("?")
    name, _, version = unquote(location).rpartition("@")
    qualifiers = {key: values[0] for key, values in parse_qs(query).items()}
    sha = next(
        (str(h["content"]) for h in component.get("hashes", []) or [] if h.get("alg") == "SHA-256"),  # type: ignore[attr-defined]
        None,
    )
    licence = _licence_expression(component)
    if qualifiers.get("download_url", "").startswith("file:"):
        return Crate(name, version, licence, "local")
    if "vcs_url" in qualifiers:
        match = GIT_VCS.match(qualifiers["vcs_url"])
        if match is None:
            raise NoticeError(f"crate {name} {version}: unsupported vcs_url {qualifiers['vcs_url']}")
        owner, repository, commit = match.groups()
        return Crate(name, version, licence, "git", (owner, repository, commit))
    if "download_url" in qualifiers:
        raise NoticeError(f"crate {name} {version}: unsupported download_url")
    return Crate(name, version, licence, "registry", sha256=sha)


def installed(site_packages: Path) -> list[Dist]:
    dists = []
    for dist_info in sorted(site_packages.glob("*.dist-info")):
        name, version = _metadata(dist_info)
        record = (dist_info / "RECORD").read_text(encoding="utf-8")
        paths = [line.split(",", 1)[0] for line in record.splitlines()]
        compiled = any(re.search(r"\.so(\.[0-9.]+)?$", path) for path in paths)
        dist = Dist(name, version, dist_info, compiled)
        for sbom in sorted((dist_info / "sboms").glob("*.json")):
            for component in json.loads(sbom.read_text(encoding="utf-8")).get("components", []):
                if (crate := _crate(component)) is not None:
                    dist.crates.append(crate)
        dists.append(dist)
    return dists


def licence_files(dist: Dist) -> list[Path]:
    return sorted(p for p in dist.path.rglob("*") if p.is_file() and LICENCE_FILE.match(p.name))


