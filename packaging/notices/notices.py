def _crates_index(text: str) -> dict[tuple[str, str], set[str]]:
    index: dict[tuple[str, str], set[str]] = {}
    current: tuple[str, str] | None = None
    for line in text.splitlines():
        if line.startswith("crate: "):
            name, version = line.removeprefix("crate: ").split(" ")
            current = (name, version)
            index[current] = set()
        elif line.startswith("used by: ") and current is not None:
            index[current] = set(line.removeprefix("used by: ").split(", "))
    return index


def check(site_packages: Iterable[Path], notices: Path = HERE) -> list[str]:
    """Problems that make the committed notices incomplete or stale; empty when they match."""
    natives, own = read_lock(notices / "native.lock")
    crates_path = notices / "crates.txt"
    crate_index = _crates_index(crates_path.read_text(encoding="utf-8")) if crates_path.exists() else {}
    embedded = {pin for native in natives for pin in native.embedded_in}
    problems: list[str] = []
    pins: set[str] = set()
    for directory in site_packages:
        for dist in installed(directory):
            pins.add(dist.pin)
            if not licence_files(dist):
                problems.append(f"{dist.pin}: no licence file in {dist.path.name}")
            registered = [crate for crate in dist.crates if crate.kind != "local"]
            if dist.compiled and not registered and dist.pin not in own and dist.pin not in embedded:
                problems.append(f"{dist.pin}: compiled code not accounted for in native.lock or an SBOM")
            for crate in registered:
                users = crate_index.get((crate.name, crate.version))
                if users is None or dist.pin not in users:
                    problems.append(f"{dist.pin}: crate {crate.name} {crate.version} has no notice")
    for native in natives:
        problems += [
            f"native.lock: {native.archive} names {pin}, which is not installed"
            for pin in native.embedded_in
            if pin not in pins
        ]
        problems += [
            f"native/{native.archive}/{member} is missing"
            for member in native.members
            if not (notices / "native" / native.archive / member).is_file()
        ]
    problems += [f"native.lock: own-code {pin} is not installed" for pin in sorted(own - pins)]
    for (name, version), users in sorted(crate_index.items()):
        problems += [
            f"crates.txt: {name} {version} names {pin}, which is not installed" for pin in sorted(users - pins)
        ]
    return problems


# copy-python


def copy_python(site_packages: Path, output: Path) -> int:
    count = 0
    for dist in installed(site_packages):
        files = licence_files(dist)
        if not files:
            raise NoticeError(f"{dist.pin}: no licence file")
        target = output / f"{normalize(dist.name)}-{dist.version}"
        for file in files:
            destination = target / file.relative_to(dist.path)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(file, destination)
        count += 1
    return count


# collect


def fetch(url: str, sha256: str | None, cache: Path) -> tuple[bytes, str]:
    if urlsplit(url).scheme != "https":
        raise NoticeError(f"refusing non-https URL {url}")
    cached = cache / hashlib.sha256(url.encode()).hexdigest()
    if cached.exists():
        data = cached.read_bytes()
    else:
        with urllib.request.urlopen(url, timeout=120) as response:  # noqa: S310 - https only, checked above
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if sha256 is not None and digest != sha256:
        raise NoticeError(f"hash mismatch for {url}")
    cache.mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data, digest


def _archive_files(data: bytes, name: str) -> Iterator[tuple[PurePosixPath, bytes]]:
    """Regular files in an archive, with paths relative to its single top directory."""
    if name.endswith(".zip"):
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            for info in archive.infolist():
                if not info.is_dir():
                    yield PurePosixPath(*PurePosixPath(info.filename).parts[1:]), archive.read(info)
        return
    with tarfile.open(fileobj=io.BytesIO(data)) as archive:
        for member in archive.getmembers():
            if member.isfile():
                extracted = archive.extractfile(member)
                if extracted is not None:
                    yield PurePosixPath(*PurePosixPath(member.name).parts[1:]), extracted.read()


def _sdist_checksums(dist: Dist, cache: Path) -> dict[tuple[str, str], str]:
    release = json.loads(fetch(f"https://pypi.org/pypi/{dist.name}/{dist.version}/json", None, cache)[0])
    sdists = [entry for entry in release["urls"] if entry["packagetype"] == "sdist"]
    if len(sdists) != 1:
        raise NoticeError(f"{dist.pin}: expected one source distribution")
    data, _ = fetch(sdists[0]["url"], sdists[0]["digests"]["sha256"], cache)
    checksums: dict[tuple[str, str], str] = {}
    for path, content in _archive_files(data, sdists[0]["filename"]):
        if path.name == "Cargo.lock":
            for package in tomllib.loads(content.decode("utf-8")).get("package", []):
                if "checksum" in package:
                    checksums[(package["name"], package["version"])] = package["checksum"]
    return checksums


def collect(site_packages: Iterable[Path], cache: Path, notices: Path = HERE) -> None:
    natives, _ = read_lock(notices / "native.lock")
    native_dir = notices / "native"
    shutil.rmtree(native_dir, ignore_errors=True)
    for native in natives:
        data, _ = fetch(native.url, native.sha256, cache)
        files = dict(_archive_files(data, native.archive))
        for member in native.members:
            content = files.get(PurePosixPath(member))
            if content is None:
                raise NoticeError(f"{native.archive}: no member {member}")
            target = native_dir / native.archive / member
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        print(f"native: {native.archive}")

    users: dict[tuple[str, str], set[str]] = {}
    crates: dict[tuple[str, str], tuple[Crate, Dist]] = {}
    for directory in site_packages:
        for dist in installed(directory):
            for crate in dist.crates:
                if crate.kind != "local":
                    users.setdefault((crate.name, crate.version), set()).add(dist.pin)
                    crates.setdefault((crate.name, crate.version), (crate, dist))
    checksums: dict[str, dict[tuple[str, str], str]] = {}
    sections = [CRATES_HEADER]
    seen: dict[str, str] = {}
    without_files: list[str] = []
    for key in sorted(crates):
        crate, dist = crates[key]
        if crate.kind == "git":
            assert crate.git is not None  # noqa: S101 - set for git crates
            owner, repository, commit = crate.git
            url, expected, archive = (
                f"https://github.com/{owner}/{repository}/archive/{commit}.tar.gz",
                None,
                f"{repository}-{commit}.tar.gz",
            )
        else:
            expected = crate.sha256
            if expected is None:
                if dist.pin not in checksums:
                    checksums[dist.pin] = _sdist_checksums(dist, cache)
                expected = checksums[dist.pin].get(key)
                if expected is None:
                    raise NoticeError(f"crate {crate.name} {crate.version}: no checksum in {dist.pin}'s Cargo.lock")
            url = f"https://static.crates.io/crates/{crate.name}/{crate.name}-{crate.version}.crate"
            archive = f"{crate.name}-{crate.version}.crate"
        data, digest = fetch(url, expected, cache)
        licence_texts = sorted(
            (licence_path, content)
            for licence_path, content in _archive_files(data, archive)
            if len(licence_path.parts) == 1 and LICENCE_FILE.match(licence_path.name)
        )
        if not licence_texts:
            without_files.append(f"{crate.name} {crate.version}")
        lines = [
            "",
            "=" * 78,
            f"crate: {crate.name} {crate.version}",
            f"declared licence: {crate.licence}",
            f"used by: {', '.join(sorted(users[key]))}",
            f"source: {url}",
            f"sha256: {digest}",
        ]
        if not licence_texts:
            lines += ["", "--- This crate ships no licence file. Its declared licence is given above."]
        for licence_path, content in licence_texts:
            text = content.decode("utf-8", errors="replace").replace("\r\n", "\n").rstrip() + "\n"
            text_hash = hashlib.sha256(text.encode()).hexdigest()
            label = f"{crate.name} {crate.version} {licence_path.name}"
            if text_hash in seen:
                lines += ["", f"--- {licence_path.name}: same text as {seen[text_hash]} above"]
            else:
                seen[text_hash] = label
                lines += ["", f"--- {licence_path.name}", "", text.rstrip()]
        sections.append("\n".join(lines) + "\n")
    (notices / "crates.txt").write_text("".join(sections), encoding="utf-8")
    print(f"crates: {len(crates)}")
    for crate_label in without_files:
        print(f"review: crate {crate_label} ships no licence file; its declared licence is recorded")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("collect", "check"):
        command = commands.add_parser(name)
        command.add_argument("--site-packages", type=Path, nargs="+", required=True)
        if name == "collect":
            command.add_argument("--cache", type=Path, default=Path(".notices-cache"))
    copy = commands.add_parser("copy-python")
    copy.add_argument("--site-packages", type=Path, required=True)
    copy.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args(argv)
    try:
        if arguments.command == "collect":
            collect(arguments.site_packages, arguments.cache)
        elif arguments.command == "check":
            problems = check(arguments.site_packages)
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                return 1
            print("notices match the installed packages")
        else:
            print(f"copied licence files for {copy_python(arguments.site_packages, arguments.output)} packages")
    except NoticeError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
