"""Write sources-python.lock and sources-crates.lock for the bundled SearXNG.

- sources-python.lock: the PyPI source distribution of every package pinned in
  requirements.lock, with PyPI's SHA-256.
- sources-crates.lock: every Rust crate in Granian's Cargo.lock, taken from
  Granian's own source distribution as pinned in sources-python.lock.
  Registry crates use the checksum Cargo.lock records. Git crates are
  downloaded as a GitHub archive of the locked commit and hashed here.

Run it after changing requirements.lock, and review the diff:

    python3 packaging/searxng/lock-sources.py

Uses only the standard library. Downloads go over verified HTTPS.
"""

from __future__ import annotations

import hashlib
import io
import json
import re
import sys
import tarfile
import tomllib
import urllib.request
from pathlib import Path
from urllib.parse import urlsplit

HERE = Path(__file__).resolve().parent
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;\\]+)")
GIT_SOURCE = re.compile(r"^git\+https://github\.com/([\w.-]+)/([\w.-]+?)(?:\.git)?(?:\?[^#]*)?#([0-9a-f]{40})$")
HEADER = "# Generated by lock-sources.py; do not edit. Columns: path  sha256  url\n"


def fetch(url: str) -> bytes:
    if urlsplit(url).scheme != "https":
        raise ValueError(f"refusing non-https URL {url}")
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 - https only, checked above
        data: bytes = response.read()
    return data


def pins() -> list[tuple[str, str]]:
    found = []
    for line in (HERE / "requirements.lock").read_text(encoding="utf-8").splitlines():
        if match := PIN.match(line):
            found.append((match[1], match[2]))
    return found


def sdist(name: str, version: str) -> tuple[str, str, str]:
    release = json.loads(fetch(f"https://pypi.org/pypi/{name}/{version}/json"))
    files = [entry for entry in release["urls"] if entry["packagetype"] == "sdist"]
    if len(files) != 1:
        raise SystemExit(f"{name}=={version}: expected one source distribution, found {len(files)}")
    return files[0]["filename"], files[0]["digests"]["sha256"], files[0]["url"]


def crates(granian_sdist: bytes) -> list[tuple[str, str, str]]:
    with tarfile.open(fileobj=io.BytesIO(granian_sdist)) as archive:
        member = next(m for m in archive.getmembers() if m.name.count("/") == 1 and m.name.endswith("/Cargo.lock"))
        extracted = archive.extractfile(member)
        assert extracted is not None  # noqa: S101 - a regular file member
        lock = tomllib.loads(extracted.read().decode("utf-8"))
    entries = []
    for package in lock["package"]:
        name, version, source = package["name"], package["version"], package.get("source")
        if source is None:
            continue  # Granian itself, already in its source distribution
        if source == "registry+https://github.com/rust-lang/crates.io-index":
            url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
            entries.append((f"{name}-{version}.crate", package["checksum"], url))
        elif match := GIT_SOURCE.match(source):
            owner, repository, commit = match.groups()
            url = f"https://github.com/{owner}/{repository}/archive/{commit}.tar.gz"
            digest = hashlib.sha256(fetch(url)).hexdigest()
            entries.append((f"{name}-{version}-{commit[:12]}.tar.gz", digest, url))
        else:
            raise SystemExit(f"crate {name} {version}: unsupported source {source}")
    return entries


def write(path: Path, rows: list[tuple[str, str, str]], directory: str) -> None:
    lines = [HEADER] + [f"{directory}/{file}  {sha}  {url}\n" for file, sha, url in sorted(rows)]
    path.write_text("".join(lines), encoding="utf-8")
    print(f"{path.name}: {len(rows)} archives")


def main() -> int:
    python_rows = [sdist(name, version) for name, version in pins()]
    write(HERE / "sources-python.lock", python_rows, "python")
    granian = next((row for row in python_rows if row[0].startswith("granian-")), None)
    if granian is None:
        raise SystemExit("granian is not pinned in requirements.lock")
    data = fetch(granian[2])
    if hashlib.sha256(data).hexdigest() != granian[1]:
        raise SystemExit("granian source distribution does not match its PyPI hash")
    write(HERE / "sources-crates.lock", crates(data), "crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
